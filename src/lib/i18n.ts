function normalizeLanguage(value?: string | null): AppLanguage {
  return value?.toLowerCase().startsWith("en") ? "en" : "ar";
}

function getInitialLanguage(): AppLanguage {
  // Always start from the same language on the server and during hydration.
  // The saved preference is applied after mount to avoid HTML mismatches.
  return "ar";
}

export function applyDocumentLanguage(language: string) {
  if (typeof document === "undefined") {
    return;
  }

  const normalized = normalizeLanguage(language);
  document.documentElement.lang = normalized;
  document.documentElement.dir = normalized === "ar" ? "rtl" : "ltr";
}

function syncResourceBundles() {
  (["ar", "en"] as const).forEach((language) => {
    i18n.addResourceBundle(
      language,
      "translation",
      resources[language].translation,
      true,
      true
    );
  });
}

if (!i18n.isInitialized) {
  void i18n.use(initReactI18next).init({
    resources,
    lng: getInitialLanguage(),
    fallbackLng: "ar",
    supportedLngs: ["ar", "en"],
    interpolation: {
      escapeValue: false,
    },
    react: {
      useSuspense: false,
    },
  });
} else {
  // i18next is a singleton. During Next.js Fast Refresh the module can be
  // re-evaluated while the existing instance stays initialized. Refresh the
  // in-memory bundles so newly added/edited translations are available now.
  syncResourceBundles();
}

